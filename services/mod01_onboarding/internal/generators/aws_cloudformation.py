"""AWS CloudFormation Template Synthesis Engine for LogRaven CSPM/CIEM Onboarding.

Generates:
1. Single-Account CloudFormation template
2. AWS Organizations StackSet template (multi-region / multi-account)
"""

import json
from typing import List, Optional
import yaml


# Safe YAML dumper representation
class IndentedYamlDumper(yaml.SafeDumper):
    def increase_indent(self, flow=False, indentless=False):
        return super().increase_indent(flow, False)


def generate_single_account_cf(
    tenant_id: str,
    external_id: str,
    lograven_account_id: str = "112233445566",
    role_name: str = "LogRavenCSPMReader",
    event_bus_region: str = "us-east-1",
) -> str:
    """Generate single-account AWS CloudFormation template."""
    event_bus_arn = f"arn:aws:events:{event_bus_region}:{lograven_account_id}:event-bus/lr-ingest-{tenant_id}"

    template = {
        "AWSTemplateFormatVersion": "2010-09-09",
        "Description": f"LogRaven Enterprise Multi-Cloud CSPM & Trust Broker Connector for Tenant {tenant_id}",
        "Parameters": {
            "ExternalId": {
                "Type": "String",
                "Default": external_id,
                "Description": "Cryptographic ExternalId generated by LogRaven Trust Broker",
                "NoEcho": True,
            },
            "LogRavenAccountId": {
                "Type": "String",
                "Default": lograven_account_id,
                "Description": "LogRaven Trusted AWS Management Account ID",
            },
            "EventBusRegion": {
                "Type": "String",
                "Default": event_bus_region,
                "Description": "Primary LogRaven ingestion region",
            },
        },
        "Resources": {
            "LogRavenReaderRole": {
                "Type": "AWS::IAM::Role",
                "Properties": {
                    "RoleName": role_name,
                    "AssumeRolePolicyDocument": {
                        "Version": "2012-10-17",
                        "Statement": [
                            {
                                "Effect": "Allow",
                                "Principal": {
                                    "AWS": {
                                        "Fn::Sub": "arn:aws:iam::${LogRavenAccountId}:root"
                                    }
                                },
                                "Action": "sts:AssumeRole",
                                "Condition": {
                                    "StringEquals": {
                                        "sts:ExternalId": {"Ref": "ExternalId"}
                                    }
                                },
                            }
                        ],
                    },
                    "ManagedPolicyArns": [
                        "arn:aws:iam::aws:policy/SecurityAudit",
                        "arn:aws:iam::aws:policy/job-function/ViewOnlyAccess",
                    ],
                    "Policies": [
                        {
                            "PolicyName": "LogRavenSupplementalTelemetry",
                            "PolicyDocument": {
                                "Version": "2012-10-17",
                                "Statement": [
                                    {
                                        "Sid": "LogRavenEventBridgeForwarding",
                                        "Effect": "Allow",
                                        "Action": ["events:PutEvents"],
                                        "Resource": event_bus_arn,
                                    },
                                    {
                                        "Sid": "LogRavenCSPMSupplementalRead",
                                        "Effect": "Allow",
                                        "Action": [
                                            "s3:GetEncryptionConfiguration",
                                            "s3:GetBucketPublicAccessBlock",
                                            "s3:GetBucketPolicyStatus",
                                            "kms:GetKeyRotationStatus",
                                            "iam:SimulatePrincipalPolicy",
                                            "access-analyzer:ListFindings",
                                        ],
                                        "Resource": "*",
                                    },
                                ],
                            },
                        }
                    ],
                },
            },
            "LogRavenTelemetryRule": {
                "Type": "AWS::Events::Rule",
                "Properties": {
                    "Name": f"lr-telemetry-{tenant_id[:8]}",
                    "Description": "Forward security findings and audit events to LogRaven EventBus",
                    "EventPattern": {
                        "source": [
                            "aws.guardduty",
                            "aws.securityhub",
                            "aws.cloudtrail",
                            "aws.iam",
                        ]
                    },
                    "State": "ENABLED",
                    "Targets": [
                        {
                            "Id": "LogRavenCentralBus",
                            "Arn": event_bus_arn,
                            "RoleArn": {"Fn::GetAtt": ["LogRavenForwardingRole", "Arn"]},
                        }
                    ],
                },
            },
            "LogRavenForwardingRole": {
                "Type": "AWS::IAM::Role",
                "Properties": {
                    "RoleName": f"lr-event-forwarder-{tenant_id[:8]}",
                    "AssumeRolePolicyDocument": {
                        "Version": "2012-10-17",
                        "Statement": [
                            {
                                "Effect": "Allow",
                                "Principal": {"Service": "events.amazonaws.com"},
                                "Action": "sts:AssumeRole",
                            }
                        ],
                    },
                    "Policies": [
                        {
                            "PolicyName": "PutEventsToLogRaven",
                            "PolicyDocument": {
                                "Version": "2012-10-17",
                                "Statement": [
                                    {
                                        "Effect": "Allow",
                                        "Action": "events:PutEvents",
                                        "Resource": event_bus_arn,
                                    }
                                ],
                            },
                        }
                    ],
                },
            },
        },
        "Outputs": {
            "RoleArn": {
                "Description": "ARN of the LogRaven Reader IAM Role",
                "Value": {"Fn::GetAtt": ["LogRavenReaderRole", "Arn"]},
            },
            "ExternalId": {
                "Description": "ExternalId configured for cross-account trust",
                "Value": {"Ref": "ExternalId"},
            },
        },
    }

    return yaml.dump(template, Dumper=IndentedYamlDumper, sort_keys=False)


def generate_aws_stackset(
    tenant_id: str,
    external_id: str,
    regions: Optional[List[str]] = None,
    lograven_account_id: str = "112233445566",
    role_name: str = "LogRavenCSPMReader",
) -> str:
    """Generate multi-region AWS Organizations CloudFormation StackSet template.
    
    Adheres to TC-MOD1-001 specification.
    """
    selected_regions = regions or ["us-east-1", "eu-west-1", "ap-south-1"]
    
    # Base template for StackSet instances
    template = {
        "AWSTemplateFormatVersion": "2010-09-09",
        "Description": f"LogRaven Enterprise AWS StackSet Template for Tenant {tenant_id}",
        "Parameters": {
            "ExternalId": {
                "Type": "String",
                "Default": external_id,
                "Description": "LogRaven tenant cryptographic ExternalId",
                "NoEcho": True,
            },
            "LogRavenAccountId": {
                "Type": "String",
                "Default": lograven_account_id,
                "Description": "LogRaven Trusted AWS Management Account ID",
            },
            "TargetRegions": {
                "Type": "CommaDelimitedList",
                "Default": ", ".join(selected_regions),
                "Description": "AWS Regions enabled for continuous telemetry streaming",
            },
        },
        "Conditions": {
            "IsPrimaryRegion": {
                "Fn::Equals": [{"Ref": "AWS::Region"}, "us-east-1"]
            }
        },
        "Resources": {
            "LogRavenReaderRole": {
                "Type": "AWS::IAM::Role",
                "Condition": "IsPrimaryRegion", # IAM roles are global, deploy once per account
                "Properties": {
                    "RoleName": role_name,
                    "AssumeRolePolicyDocument": {
                        "Version": "2012-10-17",
                        "Statement": [
                            {
                                "Effect": "Allow",
                                "Principal": {
                                    "AWS": {
                                        "Fn::Sub": "arn:aws:iam::${LogRavenAccountId}:root"
                                    }
                                },
                                "Action": "sts:AssumeRole",
                                "Condition": {
                                    "StringEquals": {
                                        "sts:ExternalId": {"Ref": "ExternalId"}
                                    }
                                },
                            }
                        ],
                    },
                    "ManagedPolicyArns": [
                        "arn:aws:iam::aws:policy/SecurityAudit",
                    ],
                    "Policies": [
                        {
                            "PolicyName": "LogRavenStackSetTelemetryPolicy",
                            "PolicyDocument": {
                                "Version": "2012-10-17",
                                "Statement": [
                                    {
                                        "Sid": "LogRavenPutEventsRestricted",
                                        "Effect": "Allow",
                                        "Action": ["events:PutEvents"],
                                        "Resource": {
                                            "Fn::Sub": f"arn:aws:events:*:*:event-bus/lr-ingest-{tenant_id}"
                                        },
                                    },
                                    {
                                        "Sid": "LogRavenAuditSimulate",
                                        "Effect": "Allow",
                                        "Action": [
                                            "iam:SimulatePrincipalPolicy",
                                            "s3:GetEncryptionConfiguration",
                                            "s3:GetBucketPublicAccessBlock",
                                            "kms:GetKeyRotationStatus",
                                        ],
                                        "Resource": "*",
                                    },
                                ],
                            },
                        }
                    ],
                },
            },
            "LogRavenRegionalEventForwarder": {
                "Type": "AWS::Events::Rule",
                "Properties": {
                    "Name": f"lr-stackset-bus-{tenant_id[:8]}",
                    "Description": "Regional EventBridge forwarder to LogRaven central bus",
                    "EventPattern": {
                        "source": ["aws.guardduty", "aws.securityhub", "aws.cloudtrail"]
                    },
                    "State": "ENABLED",
                    "Targets": [
                        {
                            "Id": "CentralEventBusTarget",
                            "Arn": {
                                "Fn::Sub": f"arn:aws:events:${{AWS::Region}}:${{LogRavenAccountId}}:event-bus/lr-ingest-{tenant_id}"
                            },
                            "RoleArn": {"Fn::GetAtt": ["LogRavenEventsRole", "Arn"]},
                        }
                    ],
                },
            },
            "LogRavenEventsRole": {
                "Type": "AWS::IAM::Role",
                "Properties": {
                    "RoleName": {
                        "Fn::Sub": f"lr-ev-role-${{AWS::Region}}-{tenant_id[:8]}"
                    },
                    "AssumeRolePolicyDocument": {
                        "Version": "2012-10-17",
                        "Statement": [
                            {
                                "Effect": "Allow",
                                "Principal": {"Service": "events.amazonaws.com"},
                                "Action": "sts:AssumeRole",
                            }
                        ],
                    },
                    "Policies": [
                        {
                            "PolicyName": "AllowPutEventsToCentralBus",
                            "PolicyDocument": {
                                "Version": "2012-10-17",
                                "Statement": [
                                    {
                                        "Effect": "Allow",
                                        "Action": "events:PutEvents",
                                        "Resource": "arn:aws:events:*:*:event-bus/lr-*",
                                    }
                                ],
                            },
                        }
                    ],
                },
            },
        },
        "Outputs": {
            "ConfiguredExternalId": {
                "Description": "ExternalId configured in StackSet",
                "Value": {"Ref": "ExternalId"},
            },
        },
    }

    return yaml.dump(template, Dumper=IndentedYamlDumper, sort_keys=False)

